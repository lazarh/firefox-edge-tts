#!/usr/bin/env bash
# Slice 5: uninstall. Restores the user to their pre-install state rather than
# just deleting files: the previous speech-dispatcher config comes back and
# espeak-ng goes back to being the default voice.
#
# Also owns --cleanup-piper, which removes leftovers from the older
# firefox-piper project after edge-tts has taken over the speech config.

# Remove the edge-tts runtime, wrapper and generated bridge.
remove_edge_runtime() {
    if [ -d "$EDGE_HOME" ]; then
        rm -rf "$EDGE_HOME"
        ok "removed edge-tts runtime"
    fi
}

remove_voice_cache() {
    if [ -d "$VOICE_CACHE_DIR" ]; then
        rm -rf "$VOICE_CACHE_DIR"
        ok "removed cached voice catalogue"
    fi
}

# Put the original speech-dispatcher config back if we saved a real one.
#
# A backup that still loads a generated module config is not a backup:
# restoring it would point the default module at a runtime that has just been
# deleted, leaving speech-dispatcher unable to speak. Refuse to restore that.
restore_speechd_config() {
    # If firefox-piper left the true original behind and this install never made
    # its own backup, use the old one as the restore point.
    if [ ! -f "$SPD_BACKUP" ] && [ -f "$SPD_PIPER_BACKUP" ] \
        && ! spd_conf_is_ours "$SPD_PIPER_BACKUP"; then
        cp -p "$SPD_PIPER_BACKUP" "$SPD_BACKUP"
    fi

    if [ -f "$SPD_BACKUP" ]; then
        if spd_conf_is_ours "$SPD_BACKUP"; then
            warn "discarding backup: it is itself a generated config"
            rm -f "$SPD_BACKUP"
            rm -f "$SPD_CONF"
            ok "removed generated speechd.conf (speech-dispatcher falls back to system defaults)"
        else
            cp -p "$SPD_BACKUP" "$SPD_CONF"
            rm -f "$SPD_BACKUP"
            ok "restored your previous speechd.conf"
        fi
    elif spd_conf_is_ours "$SPD_CONF"; then
        # Nothing was backed up, so the whole file is ours to remove.
        rm -f "$SPD_CONF"
        ok "removed generated speechd.conf (speech-dispatcher falls back to system defaults)"
    else
        warn "leaving $SPD_CONF in place: not generated by this script"
    fi
}

uninstall_all() {
    local purge_packages=no

    # Flags may arrive either before or after the subcommand.
    while [ $# -gt 0 ]; do
        case "$1" in
            --purge-packages) purge_packages=yes; shift ;;
            *) die "unknown option for uninstall: $1" ;;
        esac
    done

    info "uninstalling edge-tts from speech-dispatcher"

    # 0. Stop a warm daemon left over from an earlier build, before its files
    #    are deleted, so it cannot keep an idle websocket open.
    remove_legacy_daemon

    # 1. Restore speech-dispatcher first, so narration works again immediately.
    restore_speechd_config
    rm -f "$SPD_EDGE_CONF" "$SPD_STATE"
    rmdir "$SPD_MODULES_DIR" 2>/dev/null || true
    ok "removed the edge-tts module config"

    # 2. The runtime, generated bridge and voice catalogue.
    remove_edge_runtime
    remove_voice_cache

    # 3. Optionally the packages we installed. espeak-ng is deliberately left
    #    alone so the user keeps a working speech engine. mpg123 and jq are
    #    general-purpose tools and are left in place too.
    if [ "$purge_packages" = "yes" ]; then
        info "removing apt packages this script installed"
        sudo_ apt-get remove -y speech-dispatcher speech-dispatcher-espeak-ng \
            || warn "apt-get remove reported an error; check installed packages manually"
    else
        dim "packages left in place (speech-dispatcher, espeak-ng, mpg123, jq)"
        dim "re-run with --purge-packages to remove the speech-dispatcher packages"
    fi

    restart_speech_dispatcher

    log ""
    ok "uninstalled"
    if [ "$purge_packages" = "yes" ]; then
        dim "speech-dispatcher was removed; no TTS engine remains until it is reinstalled."
    else
        dim "espeak-ng remains the default voice, as it was before."
    fi
    log ""
}

# Remove files belonging to the older firefox-piper project. Refuses until
# edge-tts is configured, so speech-dispatcher is never left pointing at a
# module that has just been deleted.
cleanup_piper_install() {
    piper_installed_any || { log "No previous firefox-piper install found."; return 0; }

    spd_is_configured \
        || die "configure firefox-edge-tts first (run: $0 --install), so speech-dispatcher keeps working"

    info "removing the previous firefox-piper install"

    # Keep the true original speechd.conf reachable before deleting the old
    # install: inherit its backup if this install has none of its own.
    if [ ! -f "$SPD_BACKUP" ] && [ -f "$SPD_PIPER_BACKUP" ] \
        && ! spd_conf_is_ours "$SPD_PIPER_BACKUP"; then
        cp -p "$SPD_PIPER_BACKUP" "$SPD_BACKUP"
        ok "kept the firefox-piper speechd.conf backup as this install's restore point"
    fi

    rm -f "$SPD_MODULES_DIR/piper.conf" "$SPD_PIPER_STATE"
    ok "removed the Piper module config"

    local store="$HOME/.local/share/piper/voices" dir
    if [ -d "$store" ]; then
        for dir in "$store"/*/; do
            [ -d "$dir" ] || continue
            if [ -f "$dir/.installed-by-firefox-piper" ]; then
                rm -rf "$dir"
            else
                warn "keeping $dir: not installed by firefox-piper"
            fi
        done
        rmdir "$store" 2>/dev/null || true
        ok "removed Piper voices installed by the old script"
    fi

    if [ -d "$HOME/.local/share/piper-tts" ] || [ -f "$HOME/.local/bin/piper" ]; then
        rm -rf "$HOME/.local/share/piper-tts"
        rm -f "$HOME/.local/bin/piper"
        ok "removed the Piper runtime"
    fi

    rm -rf "$HOME/.cache/firefox-piper"

    restart_speech_dispatcher

    log ""
    ok "firefox-piper cleaned up; edge-tts remains configured"
    dim "apt packages are left in place"
    log ""
}
