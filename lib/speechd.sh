#!/usr/bin/env bash
# Slice 3: wire edge-tts into speech-dispatcher as a per-user sd_generic module.
#
# This is the whole path Firefox Reader Mode narrates through:
#   firefox-esr -> speech-dispatcher -> sd_generic -> edge-tts -> mpg123 -> pw-cat
#
# Verified against speech-dispatcher 0.12.1 on Debian 13:
#   * sd_generic substitutes $DATA/$VOICE into GenericExecuteSynth. $DATA MUST be
#     wrapped in single quotes: the double-quoted form mangles apostrophes
#     ("it's" becomes "it'\''s") and strips double quotes from article text.
#   * Text arrives chunked; the module owns playback via $PLAY_COMMAND.
#   * AudioOutputMethod "none" is not usable here (no spd_none.so plugin), so we
#     keep a working output method and let the module play through $PLAY_COMMAND.

SPD_DIR="$HOME/.config/speech-dispatcher"
SPD_CONF="$SPD_DIR/speechd.conf"
SPD_MODULES_DIR="$SPD_DIR/modules"
SPD_EDGE_CONF="$SPD_MODULES_DIR/edge-tts.conf"
SPD_BACKUP="$SPD_DIR/speechd.conf.firefox-edge-tts.bak"
SPD_PIPER_BACKUP="$SPD_DIR/speechd.conf.firefox-piper.bak"
SPD_PIPER_STATE="$SPD_DIR/.firefox-piper-state"
SPD_STATE="$SPD_DIR/.firefox-edge-tts-state"

MODULE_NAME="edge-tts"

# Choose an audio player for raw s16le PCM on stdin.
#
# Verified on Debian 13: `pw-play` CANNOT be used here. It accepts a filename, not
# a PCM stream, so piping into it fails with "failed to open audio file -".
# `pw-cat` is the PipeWire tool that streams raw PCM, and it needs both the
# --playback and --raw flags plus an explicit "-" filename.
#
# Order matters: PipeWire first, then PulseAudio's raw-capable paplay, then ALSA.
detect_play_command() {
    if have pw-cat; then
        printf 'pw-cat --playback --raw --rate %s --channels 1 --format s16 -\n' "$EDGE_SAMPLE_RATE"
    elif have paplay; then
        printf 'paplay --raw --format=s16le --rate=%s --channels=1 --device=default -\n' "$EDGE_SAMPLE_RATE"
    elif have aplay; then
        printf 'aplay -q -r %s -f S16_LE -c 1 -t raw -\n' "$EDGE_SAMPLE_RATE"
    else
        die "no usable audio player found (install pipewire-bin for pw-cat, or alsa-utils for aplay)"
    fi
}

# Install the generated edge-speak wrapper, with runtime paths baked in.
install_speak_wrapper() {
    local mpg123_bin tmp
    mpg123_bin=$(command -v mpg123) \
        || die "mpg123 is required to decode edge-tts audio (apt-get install mpg123)"

    mkdir -p "$EDGE_HOME"
    tmp=$(mktemp "$EDGE_SPEAK.XXXXXX") || die "cannot write to $EDGE_HOME"
    sed -e "s|__EDGE_BIN__|$EDGE_VENV/bin/edge-tts|g" \
        -e "s|__MPG123__|$mpg123_bin|g" \
        "$SCRIPT_DIR/lib/edge-speak.sh.in" > "$tmp"
    chmod +x "$tmp"
    mv "$tmp" "$EDGE_SPEAK" || { rm -f "$tmp"; die "could not install $EDGE_SPEAK"; }
}

write_module_config() {
    local voice=$1 play_cmd=$2 locale=$3 gender=$4
    local lang_short="${locale%%-*}"

    # Register the voice under the BARE language subtag, not the full locale.
    #
    # Firefox's Narrate UI filters voices with `v.lang.split("-")[0] == language`,
    # so a voice registered as "bg-BG" never matches the page language "bg". The
    # Listen button is hidden entirely when that filter yields nothing, which is
    # why the voice must be "bg" to match what espeak-ng registers.
    mkdir -p "$SPD_MODULES_DIR"

    # $DATA is single-quoted on purpose. Verified on speech-dispatcher 0.12.1: the
    # double-quoted form mangles apostrophes in article text ("it's" arrives as
    # "it'\''s") and silently strips double quotes.
    # Write to a temp file and move it into place, so a failed write can never
    # leave speech-dispatcher with a truncated (or empty) module config.
    local tmp
    tmp=$(mktemp "$SPD_EDGE_CONF.XXXXXX") || die "cannot write to $SPD_MODULES_DIR"

    cat > "$tmp" <<CONF
# Generated by firefox-edge-tts -- edit with the script, not by hand.
Debug 0

# Feed the utterance to edge-speak on stdin; it returns raw s16le PCM, which
# \$PLAY_COMMAND plays. edge-tts errors go to stderr and appear in the module log.
GenericExecuteSynth \
"printf %s '\$DATA' | '$EDGE_SPEAK' --voice '$voice' --rate \$RATE | $play_cmd"

GenericCmdDependency "$EDGE_SPEAK"
GenericSoundIconFolder "/usr/share/sounds/sound-icons/"

# edge-tts interprets punctuation itself, so pass it all through untouched.
GenericPunctNone ""
GenericPunctSome ""
GenericPunctMost ""
GenericPunctAll ""

# Required: without an explicit utf-8 charset, sd_generic recodes the utterance to
# a non-UTF-8 charset and every non-Latin character arrives as '?'. Verified on
# speech-dispatcher 0.12.1 -- Bulgarian text was destroyed without this line.
GenericDefaultCharset "utf-8"
GenericLanguage "$lang_short" "${locale//-/_}" "utf-8"

# Map speech-dispatcher's rate/pitch/volume onto the values edge-speak expects.
GenericRateMultiply 1
GenericRateAdd 1
GenericPitchMultiply 1
GenericVolumeMultiply 1

AddVoice "$lang_short" "$gender" "$voice"
DefaultVoice "$voice"
CONF

    mv "$tmp" "$SPD_EDGE_CONF" || { rm -f "$tmp"; die "could not install $SPD_EDGE_CONF"; }
}

# True when a speechd.conf was written by firefox-edge-tts.
spd_conf_is_generated() {
    grep -q "Generated by firefox-edge-tts" "$1" 2>/dev/null
}

# True when a speechd.conf was written by the older firefox-piper project.
spd_conf_is_piper_generated() {
    grep -q "Generated by firefox-piper" "$1" 2>/dev/null
}

spd_conf_is_ours() {
    spd_conf_is_generated "$1" || spd_conf_is_piper_generated "$1"
}

# A firefox-piper install may have saved the user's true original config. If
# this install has no backup of its own yet, inherit that one instead of losing
# it when the old install is cleaned up.
adopt_piper_backup() {
    [ -f "$SPD_PIPER_BACKUP" ] || return 0
    [ -f "$SPD_BACKUP" ] && return 0
    # Only inherit while the active config is one of ours; otherwise the current
    # config is the thing that needs backing up.
    spd_conf_is_ours "$SPD_CONF" || [ ! -f "$SPD_CONF" ] || return 0
    if spd_conf_is_ours "$SPD_PIPER_BACKUP"; then
        dim "ignoring the firefox-piper backup: it is itself a generated config"
        return 0
    fi
    cp -p "$SPD_PIPER_BACKUP" "$SPD_BACKUP" \
        && ok "adopted the previous firefox-piper speechd.conf backup"
}

write_main_config() {
    local lang_short=$1
    mkdir -p "$SPD_DIR"

    # Preserve any pre-existing user config so --uninstall can restore it exactly.
    #
    # Only back up a config this project did not write. Re-running --install
    # overwrites speechd.conf with a fresh generated one, and backing that up
    # would make --uninstall "restore" a config that still loads the edge-tts
    # module -- pointing at a voice and runtime that have just been deleted,
    # leaving speech-dispatcher with a broken default module.
    adopt_piper_backup
    if [ -f "$SPD_CONF" ] && [ ! -f "$SPD_BACKUP" ] && ! spd_conf_is_ours "$SPD_CONF"; then
        cp -p "$SPD_CONF" "$SPD_BACKUP"
        ok "backed up your existing speechd.conf"
    fi

    local tmp
    tmp=$(mktemp "$SPD_CONF.XXXXXX") || die "cannot write to $SPD_DIR"

    cat > "$tmp" <<CONF
# Generated by firefox-edge-tts -- edit with the script, not by hand.
LogLevel 3

# edge-tts (sd_generic) is the module Firefox Reader Mode narrates through.
AddModule "$MODULE_NAME" "sd_generic" "edge-tts.conf"
DefaultModule "$MODULE_NAME"
DefaultLanguage "$lang_short"

# Route this language to edge-tts; espeak-ng stays installed as the fallback for
# everything else.
LanguageDefaultModule "$lang_short" "$MODULE_NAME"

# The sd_generic module plays audio itself through \$PLAY_COMMAND; speech-dispatcher
# uses this method only for sound icons and module status sounds.
AudioOutputMethod "libao"
Include "clients/*.conf"
CONF

    mv "$tmp" "$SPD_CONF" || { rm -f "$tmp"; die "could not install $SPD_CONF"; }
}

record_state() {
    local voice_key=$1 locale=$2 gender=$3 had_backup=$4
    cat > "$SPD_STATE" <<STATE
voice=$voice_key
lang=$locale
gender=$gender
backup=$had_backup
module_conf=$SPD_EDGE_CONF
main_conf=$SPD_CONF
installed_by=firefox-edge-tts
STATE
}

configure_speech_dispatcher() {
    local voice_key=$1
    local idx locale gender play_cmd had_backup=no

    idx=$(voices_index)
    locale=$(voice_locale "$idx" "$voice_key")
    [ -n "$locale" ] || die "could not determine the locale for $voice_key"
    gender=$(voice_type "$idx" "$voice_key")

    [ -f "$SPD_CONF" ] && had_backup=yes

    info "configuring per-user speech-dispatcher (voice: $voice_key, locale: $locale)"

    install_speak_wrapper
    play_cmd=$(detect_play_command)
    dim "player: $play_cmd"
    dim "sample rate: $EDGE_SAMPLE_RATE Hz"

    write_module_config "$voice_key" "$play_cmd" "$locale" "$gender"
    write_main_config "${locale%%-*}"
    record_state "$voice_key" "$locale" "$gender" "$had_backup"

    ok "speech-dispatcher configured"
}

# The daemon's comm is truncated to 15 chars ("speech-dispatche"), so `pgrep -x
# speech-dispatcher` can never match. Match on the comm-prefixed pattern instead,
# and anchor on the full path so module processes (sd_generic) are not matched.
spd_daemon_running() {
    pgrep -f '^/usr/bin/speech-dispatcher|^speech-dispatcher' >/dev/null 2>&1
}

# Restart the daemon so it picks up a changed config.
#
# `spd-say -x` is EXIT, not "reload": it terminates the daemon outright. Killing
# and restarting is the way to reload, and the daemon is autospawned on the next
# client connection, so a stopped daemon is never a problem.
restart_speech_dispatcher() {
    spd_daemon_running || { dim "speech-dispatcher not running; it will start on demand"; return 0; }

    info "restarting speech-dispatcher"
    # Match only the daemon itself, never a caller that merely mentions
    # "speech-dispatcher" on its command line (e.g. this script), and never the
    # short-lived module processes it forks.
    pkill -f '^/usr/bin/speech-dispatcher|^speech-dispatcher' >/dev/null 2>&1 || true

    # Wait for the old daemon to exit so its socket is not reused mid-flight.
    local waited=0
    while spd_daemon_running && [ "$waited" -lt 20 ]; do
        sleep 0.25
        waited=$((waited + 1))
    done

    # Nudge it back into existence by connecting a client.
    if have spd-say; then
        spd-say -C "" >/dev/null 2>&1 || true
    fi

    if spd_daemon_running; then
        ok "speech-dispatcher restarted"
    else
        dim "speech-dispatcher will start on next use"
    fi
}

spd_is_configured() {
    [ -f "$SPD_EDGE_CONF" ] && [ -f "$SPD_CONF" ] \
        && grep -q "AddModule \"$MODULE_NAME\"" "$SPD_CONF" 2>/dev/null
}
