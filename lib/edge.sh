#!/usr/bin/env bash
# Slice 1: system dependencies and the edge-tts runtime.
#
# edge-tts is a Python package that talks to Microsoft Edge's online speech
# service. It installs with pip into a private venv, needs no root, and does not
# touch the system Python.
#
# The service returns MP3 (24 kHz mono, 48 kbps). mpg123 decodes that to the raw
# s16le stream speech-dispatcher's player pipeline expects.

# 7.3.0 introduced the current Sec-MS-GEC v2 service token.
EDGE_MIN_VERSION="7.3.0"
EDGE_PACKAGE="edge-tts"

# Debian packages we depend on. speech-dispatcher and espeak-ng are kept as the
# espeak fallback rather than replaced. mpg123 decodes edge-tts's MP3 output;
# jq reads the cached voice catalogue.
REQUIRED_PACKAGES=(
    "speech-dispatcher"
    "speech-dispatcher-espeak-ng"
    "python3-venv"
    "jq"
    "mpg123"
)

# edge-tts runs from a private venv, so the system Python must be able to
# create one.
require_python() {
    have python3 || die "python3 is required to install edge-tts (apt-get install python3-venv)"
    python3 -c 'import venv' 2>/dev/null \
        || die "python3-venv is missing (apt-get install python3-venv)"
}

missing_packages() {
    local pkg
    for pkg in "${REQUIRED_PACKAGES[@]}"; do
        dpkg-query -W -f='${Status}' "$pkg" 2>/dev/null | grep -q "ok installed" || printf '%s\n' "$pkg"
    done
}

install_dependencies() {
    local missing
    missing=$(missing_packages | tr '\n' ' ')
    missing=${missing% }
    if [ -z "$missing" ]; then
        ok "system dependencies present"
        return 0
    fi

    info "installing system dependencies: $missing"
    info "this needs root (apt) access"
    sudo_ apt-get update -qq || die "apt-get update failed"
    # shellcheck disable=SC2086
    sudo_ apt-get install -y --no-install-recommends $missing \
        || die "apt-get install failed for: $missing"
    ok "system dependencies installed"
}

# espeak-ng stays installed and reachable so `--uninstall` can restore it as the
# default voice. We only assert it is present, never remove it.
require_espeak_fallback() {
    dpkg-query -W -f='${Status}' speech-dispatcher-espeak-ng 2>/dev/null | grep -q "ok installed" \
        || warn "speech-dispatcher-espeak-ng is missing; uninstall will not be able to restore it automatically."
}

install_edge_runtime() {
    local version

    if edge_available; then
        version=$(edge_version)
        if [ "$version" != "unknown" ] && version_ge "$version" "$EDGE_MIN_VERSION"; then
            ok "edge-tts $version already installed"
            return 0
        fi
        info "upgrading edge-tts (found ${version:-unknown}, need >= $EDGE_MIN_VERSION)"
    else
        require_python
        mkdir -p "$EDGE_HOME/bin"

        if [ ! -x "$EDGE_VENV/bin/edge-tts" ]; then
            info "creating a private Python environment for edge-tts"
            python3 -m venv "$EDGE_VENV" || die "could not create a venv at $EDGE_VENV"

            info "installing $EDGE_PACKAGE (this can take a minute)"
            "$EDGE_VENV/bin/pip" install --quiet --upgrade pip \
                || warn "could not upgrade pip inside the venv; continuing"
            "$EDGE_VENV/bin/pip" install --quiet "$EDGE_PACKAGE" \
                || die "failed to install $EDGE_PACKAGE into $EDGE_VENV"
        fi
        version=$(edge_version)
    fi

    if [ "$version" = "unknown" ] || ! version_ge "$version" "$EDGE_MIN_VERSION"; then
        "$EDGE_VENV/bin/pip" install --quiet --upgrade "$EDGE_PACKAGE" \
            || die "failed to upgrade $EDGE_PACKAGE"
        version=$(edge_version)
    fi

    # Thin wrapper so the speech-dispatcher config has one stable path to call,
    # independent of where pip placed the venv entry point. Deliberately not
    # ~/.local/bin/edge-tts, so an existing edge-tts command is left untouched.
    cat > "$EDGE_BIN" <<WRAPPER
#!/usr/bin/env bash
# Generated by firefox-edge-tts. Runs edge-tts from its private venv.
exec "$EDGE_VENV/bin/edge-tts" "\$@"
WRAPPER
    chmod +x "$EDGE_BIN"

    edge_available || die "edge-tts installed but not runnable at $EDGE_BIN"

    version=$(edge_version)
    if [ "$version" != "unknown" ] && ! version_ge "$version" "$EDGE_MIN_VERSION"; then
        die "edge-tts $version is older than the required $EDGE_MIN_VERSION"
    fi

    ok "edge-tts $version installed ($EDGE_VENV)"
}

# Compare dotted versions: returns success when $1 >= $2.
version_ge() {
    [ "$(printf '%s\n%s\n' "$2" "$1" | sort -V | head -1)" = "$2" ]
}

edge_available() {
    [ -x "$EDGE_BIN" ] && "$EDGE_BIN" --version >/dev/null 2>&1
}

# Read the installed distribution's version. edge-tts --version prints a human
# string; asking the venv's Python for metadata is stable and works even when
# the entry point itself is missing or broken.
edge_version() {
    local v
    [ -x "$EDGE_VENV/bin/python" ] || { printf '%s\n' "unknown"; return 0; }
    v=$("$EDGE_VENV/bin/python" -c \
        "import importlib.metadata as m; print(m.version('$EDGE_PACKAGE'))" 2>/dev/null) || v=""
    printf '%s\n' "${v:-unknown}"
}

# True when leftovers from the older firefox-piper project are present.
# --cleanup-piper removes them, but only after edge-tts is configured.
piper_installed_any() {
    [ -d "$HOME/.local/share/piper-tts" ] \
        || [ -f "$HOME/.local/bin/piper" ] \
        || [ -f "$SPD_MODULES_DIR/piper.conf" ] \
        || [ -d "$HOME/.local/share/piper/voices" ]
}

warn_if_piper_installed() {
    piper_installed_any || return 0
    warn "a previous firefox-piper install was found"
    dim "the new install will replace its speech-dispatcher config;"
    dim "after it works, remove the old files with: $0 --cleanup-piper"
}
